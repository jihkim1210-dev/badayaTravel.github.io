// 지출 장소·항목, 주문 상태 등 데이터에 저장되는 값은 항상 한국어로 저장하고, 보여줄 때만 t() 로 바꿉니다.

const KEY = 'badaya.lang';
let lang = 'ko';
try { if (localStorage.getItem(KEY) === 'en') lang = 'en'; } catch { /* 저장소 사용 불가 */ }

export const getLang = () => lang;

export function setLang(l) {
  lang = l === 'en' ? 'en' : 'ko';
  try { localStorage.setItem(KEY, lang); } catch { /* 저장소 사용 불가 */ }
}

// 날짜·시간 표시 형식
export const locale = () => (lang === 'en' ? 'en-GB' : 'ko-KR');

export function t(ko, vars) {
  let s = lang === 'en' && EN[ko] !== undefined ? EN[ko] : ko.replace(/§.*$/, '');
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

